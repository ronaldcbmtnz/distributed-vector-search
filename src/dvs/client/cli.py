"""Command-line interface installed as ``dvs``."""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from dvs.client import APIError, ClientError, DVSClient
from dvs.client.load import load_dataset


def _json_value(value: str, label: str) -> Any:
    try:
        if value.startswith("@"):
            return json.loads(Path(value[1:]).read_text(encoding="utf-8"))
        return json.loads(value)
    except (OSError, json.JSONDecodeError) as exc:
        raise argparse.ArgumentTypeError(f"{label} must be valid JSON or @path/to/file") from exc


def _add_vector(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--vector", required=True, help="Vector as JSON, for example '[1, 0]'")


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="dvs", description="Distributed Vector Search client")
    parser.add_argument(
        "--base-url", help="Gateway URL(s), comma-separated; defaults to DVS_BASE_URL"
    )
    parser.add_argument("--api-key", help="API key; defaults to DVS_API_KEY")
    parser.add_argument(
        "--timeout",
        type=float,
        default=float(os.environ.get("DVS_TIMEOUT_SECONDS", "5")),
        help="Per-attempt HTTP timeout in seconds",
    )
    parser.add_argument(
        "--retries",
        type=int,
        default=int(os.environ.get("DVS_MAX_RETRIES", "3")),
        help="Maximum retries for transient failures",
    )
    parser.add_argument("--history", help="Append JSONL operation history to this file")
    parser.add_argument("--client-id", help="Stable ID to write into operation history")

    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("health", help="Check gateway readiness")
    commands.add_parser("metrics", help="Read API metrics")
    commands.add_parser("admin-status", help="Read replica status (admin key required)")

    upsert = commands.add_parser("upsert", help="Create or replace a vector")
    upsert.add_argument("collection")
    upsert.add_argument("id")
    _add_vector(upsert)
    upsert.add_argument("--metadata", help="Metadata object as JSON")
    upsert.add_argument("--request-id", help="Stable idempotency key; generated if omitted")

    insert = commands.add_parser("insert", help="Insert a vector only if its ID is new")
    insert.add_argument("collection")
    insert.add_argument("id")
    _add_vector(insert)
    insert.add_argument("--metadata", help="Metadata object as JSON")
    insert.add_argument("--request-id", help="Stable idempotency key; generated if omitted")

    update = commands.add_parser("update", help="Update an existing vector")
    update.add_argument("collection")
    update.add_argument("id")
    update.add_argument("--vector", help="Replacement vector as JSON")
    update.add_argument("--metadata", help="Replacement metadata object as JSON")
    update.add_argument("--request-id", help="Stable idempotency key; generated if omitted")

    delete = commands.add_parser("delete", help="Delete a vector")
    delete.add_argument("collection")
    delete.add_argument("id")
    delete.add_argument("--request-id", help="Stable idempotency key; generated if omitted")

    get = commands.add_parser("get", help="Read one vector")
    get.add_argument("collection")
    get.add_argument("id")
    get.add_argument(
        "--consistency", choices=("eventual", "read_your_writes", "strong"), default="eventual"
    )
    get.add_argument("--min-seq", type=int)

    batch = commands.add_parser("batch", help="Upsert a JSON array of vectors")
    batch.add_argument("collection")
    batch.add_argument("--items", required=True, help="JSON array, or @path to a JSON file")

    load = commands.add_parser("load", help="Load a dataset generated by experiments.data_gen")
    load.add_argument("collection")
    load.add_argument(
        "--data-dir", required=True, help="Dataset directory containing manifest.json"
    )
    load.add_argument(
        "--batch-size", type=int, default=1000, help="Upserts per HTTP batch (1..1000)"
    )

    search = commands.add_parser("search", help="Search for nearest vectors")
    search.add_argument("collection")
    _add_vector(search)
    search.add_argument("--k", type=int, default=10)
    search.add_argument("--filter", help="Contract filter object as JSON")
    search.add_argument(
        "--consistency", choices=("eventual", "read_your_writes", "strong"), default="eventual"
    )
    search.add_argument("--tokens", help="RYW token array as JSON, if supplied")
    search.add_argument("--allow-partial", action=argparse.BooleanOptionalAction, default=True)
    search.add_argument("--deadline-ms", type=int)
    return parser


def _decode_optional(value: str | None, label: str) -> Any:
    return _json_value(value, label) if value is not None else None


def _invoke(client: DVSClient, args: argparse.Namespace) -> dict[str, Any]:
    command = args.command
    if command in {"health", "metrics", "admin-status"}:
        return getattr(client, command.replace("-", "_"))()
    if command in {"upsert", "insert"}:
        method = getattr(client, command)
        return method(
            args.collection,
            args.id,
            _json_value(args.vector, "vector"),
            _decode_optional(args.metadata, "metadata"),
            request_id=args.request_id,
        )
    if command == "update":
        kwargs: dict[str, Any] = {"request_id": args.request_id}
        if args.vector is not None:
            kwargs["vector"] = _json_value(args.vector, "vector")
        if args.metadata is not None:
            kwargs["metadata"] = _json_value(args.metadata, "metadata")
        return client.update(args.collection, args.id, **kwargs)
    if command == "delete":
        return client.delete(args.collection, args.id, request_id=args.request_id)
    if command == "get":
        return client.get(
            args.collection,
            args.id,
            consistency=args.consistency,
            min_seq=args.min_seq,
        )
    if command == "batch":
        items = _json_value(args.items, "items")
        if not isinstance(items, list):
            raise ValueError("items must be a JSON array")
        return client.batch(args.collection, items)
    if command == "load":
        return load_dataset(
            client,
            args.collection,
            args.data_dir,
            batch_size=args.batch_size,
        )
    if command == "search":
        filter_value = _decode_optional(args.filter, "filter")
        tokens = _decode_optional(args.tokens, "tokens")
        if tokens is not None and not isinstance(tokens, list):
            raise ValueError("tokens must be a JSON array")
        return client.search(
            args.collection,
            _json_value(args.vector, "vector"),
            k=args.k,
            filter=filter_value,
            consistency=args.consistency,
            tokens=tokens,
            allow_partial=args.allow_partial,
            deadline_ms=args.deadline_ms,
        )
    raise ValueError(f"unsupported command: {command}")


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        with DVSClient(
            base_url=args.base_url,
            api_key=args.api_key,
            timeout=args.timeout,
            max_retries=args.retries,
            history_path=args.history,
            client_id=args.client_id,
        ) as client:
            result = _invoke(client, args)
        print(json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False))
        return 0
    except (ClientError, ValueError, TypeError, argparse.ArgumentTypeError) as exc:
        if isinstance(exc, APIError):
            label = f"HTTP {exc.status_code} {exc.error_code or ''}".strip()
            request_id = f" (request_id={exc.request_id})" if exc.request_id else ""
            print(f"{label}: {exc}{request_id}", file=sys.stderr)
        else:
            request_id = f" (request_id={exc.request_id})" if exc.request_id else ""
            print(f"dvs: {exc}{request_id}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
